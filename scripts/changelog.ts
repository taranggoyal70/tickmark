/**
 * Writes CHANGELOG.md from git history. The file is generated: edit commit
 * messages, not the changelog.
 *
 *   npm run changelog
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const SECTIONS: [RegExp, string][] = [
  [/^feat(\(.+\))?!?:/i, "Added"],
  [/^fix(\(.+\))?!?:/i, "Fixed"],
  [/^(docs|test|ci|build|chore|refactor|perf)(\(.+\))?!?:/i, "Maintenance"],
];

const log = execFileSync("git", ["log", "--no-merges", "--date=short", "--format=%h%x09%ad%x09%s"], { encoding: "utf8" })
  .trim().split("\n").filter(Boolean)
  .map((line) => { const [hash, date, subject] = line.split("\t"); return { hash, date, subject }; })
  .filter((c) => !/^Initial commit from Create Next App$/.test(c.subject));

const months = new Map<string, typeof log>();
for (const c of log) {
  const m = c.date.slice(0, 7);
  (months.get(m) ?? months.set(m, []).get(m)!).push(c);
}

const out = [
  "# Changelog",
  "",
  "<!-- Generated by `npm run changelog` from git history. Do not edit by hand. -->",
  "",
  "Tickmark has no tagged releases yet; changes are grouped by month, newest first.",
  "",
];
for (const [month, commits] of months) {
  out.push(`## ${month}`, "");
  const grouped = new Map<string, string[]>();
  for (const c of commits) {
    const section = SECTIONS.find(([re]) => re.test(c.subject))?.[1] ?? "Changed";
    const text = c.subject.replace(/^\w+(\(.+\))?!?:\s*/, "");
    (grouped.get(section) ?? grouped.set(section, []).get(section)!).push(`- ${text[0].toUpperCase()}${text.slice(1)} (${c.hash})`);
  }
  for (const section of ["Added", "Fixed", "Changed", "Maintenance"]) {
    const items = grouped.get(section);
    if (items) out.push(`### ${section}`, "", ...items, "");
  }
}
writeFileSync("CHANGELOG.md", out.join("\n"));
console.log(`wrote CHANGELOG.md (${log.length} commits)`);
